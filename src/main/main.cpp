// First-run ROM setup helpers. These run in main() BEFORE recomp::start(), i.e. before the renderer
// and before ultramodern's message-box callback exist. Static recompilation ships no game data — the
// player supplies their own legally-dumped ROM, which librecomp validates by hash and caches in the
// config directory so it's only requested once.
// ---------------------------------------------------------------------------------------------------

// Show a player-facing dialog and log the same text. SDL_ShowSimpleMessageBox works with no window,
// unlike the stderr-only message_box() above (which nobody sees when launched from a GUI/launcher).
static void bar_user_message(uint32_t sdl_flags, const char* msg) {
    std::fprintf(stderr, "[beetle-adventure-racing-recomp] %s\n", msg);
#ifdef BEETLE_ENABLE_FRONTEND
    // The release build is /SUBSYSTEM:WINDOWS, so stderr goes nowhere a player will ever look.
    SDL_ShowSimpleMessageBox(sdl_flags, "Beetle Adventure Racing: Recompiled", msg, nullptr);
#else
    // The headless build keeps stderr only: a modal box would hang an automated run.
    (void)sdl_flags;
#endif
}

// Human-readable explanation for a ROM validation failure.
static const char* bar_rom_error_text(recomp::RomValidationError err) {
    switch (err) {
        case recomp::RomValidationError::FailedToOpen:     return "The selected file could not be opened.";
        case recomp::RomValidationError::NotARom:          return "That file doesn't look like a Nintendo 64 ROM.";
        case recomp::RomValidationError::IncorrectRom:     return "That isn't a Beetle Adventure Racing ROM.";
        case recomp::RomValidationError::IncorrectVersion: return "Wrong version - this port needs the USA release of Beetle Adventure Racing.";
        case recomp::RomValidationError::NotYet:           return "That ROM is recognized but isn't supported yet.";
        default:                                           return "The ROM could not be loaded.";
    }
}

// Validate `path` and, on success, cache it in the config dir (start_game() then loads it from there).
// On failure, explain why to the player. Returns true only when a valid ROM is now stored.
static bool bar_select_and_report(const std::filesystem::path& path, std::u8string& game_id) {
    recomp::RomValidationError err = recomp::select_rom(path, game_id);
    if (err == recomp::RomValidationError::Good) {
        g_default_rom_path = path;   // keep bar_ui's (non-boot) "Play" request in sync
        return true;
    }
    bar_user_message(SDL_MESSAGEBOX_ERROR,
        (std::string(bar_rom_error_text(err)) + "\n\n" + path.string()).c_str());
    return false;
}

int main(int argc, char** argv) {
    (void)argc; (void)argv;
#ifdef _WIN32
    { extern void bar_install_crash_handler(); bar_install_crash_handler(); }   // symbolized backtrace on AV
#endif
#ifdef _WIN32
    // Raise the Windows timer resolution to 1ms. CRITICAL for menu/sparse-workload framerate: the game's
    // VI-synced RCP scheduler + our runtime's gfx/task threads hand work off via timed waits. At the default
    // ~15.6ms timer resolution, each wake quantizes to ~15.6ms, so a single gfx round-trip costs ~2 quanta
    // (~32ms) and a menu frame several — capping the menu at ~10fps. (A race never waits — it always has gfx
    // queued — so it was unaffected and this was wrongly dismissed as "jitter only".) winmm is linked.
    if (std::getenv("BAR_NO_TIMER_FIX") == nullptr) timeBeginPeriod(1);  // R6 bisect: BAR_NO_TIMER_FIX=1 reverts this menu-FPS fix
#endif

    recomp::Version project_version{};
    if (!recomp::Version::from_string(version_string, project_version)) {
        message_box(("Invalid version string: " + version_string).c_str());
        return EXIT_FAILURE;
    }

    // Config/save directory: a real per-user folder (%LOCALAPPDATA%\beetle-adventure-racing-recomp on Windows;
    // ~/.config/beetle-adventure-racing-recomp on Linux), or the exe dir when a portable.txt is present. librecomp
    // writes saves / mod config here.
    recomp::register_config_path(bar::config::get_app_config_directory());

    // Load persisted graphics settings (or write defaults on first run) and push them into the
    // runtime. This also enables RT64 high-FPS frame interpolation: the default config sets
    // rr_option = Display, so presentation tracks the monitor refresh while the game/VI/audio
    // clock stays locked at its native 60 Hz (identical game speed — see
    // docs/SETTINGS_MENU_AND_HIGH_FPS.md). Must run before recomp::start() so the renderer reads
    // it when it constructs the RT64 context.
    bar::config::load_and_apply_graphics();

    // Load persisted controller/input settings (input.json) and push them into the live 4-port input
    // path. The Controls dialog edits the same config; ports 1-3 default to unplugged so single-player
    // behavior is unchanged. Must run before recomp::start() so the first controller poll sees it.
    //
    // FIRST-RUN DEFAULT: if a game controller is plugged in the very first time we run (no input.json
    // yet), default port 1 to that controller with the "Default Gamepad" map; otherwise keep the
    // keyboard default. We enumerate here with a minimal early SDL_Init (idempotent — create_gfx
    // re-inits the full set); the device-level GUID matches what bar_input later opens.
    {
        const bool first_run = !bar::input_config::config_file_exists();
        bar::input_config::InputConfig cfg = bar::input_config::load();   // writes keyboard default on first run
        if (first_run) {
            SDL_SetMainReady();
            SDL_Init(SDL_INIT_GAMECONTROLLER);
            std::string guid, name;
            for (int i = 0; i < SDL_NumJoysticks(); i++) {
                if (!SDL_IsGameController(i)) continue;
                char buf[33] = {};
                SDL_JoystickGetGUIDString(SDL_JoystickGetDeviceGUID(i), buf, sizeof(buf));
                const char* nm = SDL_GameControllerNameForIndex(i);
                guid = buf;
                name = (nm != nullptr && *nm != '\0') ? nm : "Controller";
                break;
            }
            if (!guid.empty()) {
                using namespace bar::input_config;
                cfg.ports[0].connected    = true;
                cfg.ports[0].device       = DeviceRef{ DeviceType::Gamepad, guid, name, {} };
                cfg.ports[0].profile_name = "Default Gamepad";
                if (const BindingProfile* pr = find_profile(cfg, "Default Gamepad")) cfg.ports[0].bindings = pr->bindings;
                set(cfg);   // persist the controller default so it sticks
                std::fprintf(stderr, "[beetle-adventure-racing-recomp] first run: defaulting port 1 to controller \"%s\"\n", name.c_str());
            }
        }
        bar::input::set_config(cfg);
    }

    // Load persisted cheat toggles (applied per-frame from the SI hook once the game runs; also
    // editable live via the in-game cheats menu — F1).
    bar_cheats::load();

    // Teach librecomp about BAR (hash / entrypoint / save type).
    for (const auto& game : supported_games) {
        recomp::register_game(game);
    }

    // Wire the generated section/overlay tables so BAR's ~130 relocatable modules resolve at runtime.
    bar_register_overlays();
    // TODO(BAR): bar::register_patches(); once patches exist.

    // ---- ROM source ----
    // Resolution order: a ROM already validated + cached in the config dir from a previous run
    // (is_rom_valid) > an explicit path argument (dev / CLI) > a native "Open ROM" picker on first
    // run. select_rom() validates the hash and copies the ROM into the config dir; start_game() then
    // loads it back from there, so the player is only ever asked for the ROM once.
    std::u8string game_id = supported_games[0].game_id;
    recomp::check_all_stored_roms();                 // populate is_rom_valid() from the config dir
    bool have_rom = recomp::is_rom_valid(game_id);

    // An explicit path (e.g. `beetle-adventure-racing-recomp "C:\path\Beetle.z64"`) wins and is re-validated + cached.
    if (!have_rom && argc > 1) {
        have_rom = bar_select_and_report(std::filesystem::path(argv[1]), game_id);
    }

    // No ROM yet: how that is handled depends on which build this is.
    //
    // The frontend build must NOT bail out here. Its launcher already owns the decision --
    // add_start_game_or_load_rom_option() (see src/frontend/bar_frontend.cpp) shows "Load ROM" until
    // librecomp reports a valid ROM, runs the picker, and calls start_game() itself. Exiting here
    // would run before the launcher ever appeared, so a fresh install could never reach it: the whole
    // first-run experience of a released build was a message box saying to pass a path on the command
    // line. This block used to be guarded on BEETLE_ENABLE_UI, which the bespoke-UI removal in 019305c
    // left defined by nothing, so the frontend fell through to the headless branch.
    //
    // The headless build has no launcher and nothing else will ask, so there it is still a hard stop.
#ifndef BEETLE_ENABLE_FRONTEND
    if (!have_rom) {
        message_box("No ROM configured. Pass the ROM path as the first argument "
                    "(this build has the in-game picker disabled).");
        return EXIT_FAILURE;
    }
#endif
    (void)have_rom;

    // Coordinator: the game thread blocks in wait_for_game_started() until start_game() runs. The VI
    // thread only seeds a dummy OSViMode while !is_game_started(); starting before its first tick
    // makes update_vi() deref a null mode — so we wait for g_bar_vi_ticked (renderer presented a
    // frame, which also means the launcher can draw over it). recomp::start() below blocks the main
    // thread, so this runs on a detached thread.
#ifndef BEETLE_ENABLE_FRONTEND
    // Auto-start, for builds WITHOUT the RecompFrontend launcher.
    //
    // Not used with the frontend, for two reasons. Correctness: recompui's
    // add_start_game_or_load_rom_option() calls recomp::start_game() itself once librecomp reports a
    // valid ROM (and runs the ROM picker when it does not), so the launcher owns that decision and
    // auto-starting would race it. And safety: the wait below is on g_bar_vi_ticked, which is set by
    // src/main/rt64_render_context.cpp -- the context the frontend REPLACES. Nothing would ever set
    // it, so this fell through the full 5s timeout and started the game before the VI thread had
    // ticked, which is exactly the null-mode deref the comment below warns about. That was a silent
    // crash roughly nine seconds after launch.
    std::thread([game_id]() {
        using namespace std::chrono_literals;
        for (int i = 0; i < 500 && !g_bar_vi_ticked.load(); i++) {
            std::this_thread::sleep_for(10ms);
        }

        // The ROM was already validated + cached in main(); start_game() loads it from the config dir.
        // Start the game right away — do NOT wait for "Play". The launcher/settings/cheats menu is an
        // OVERLAY drawn over the running game: RT64 only drives the UI's render+input render-hook while
        // the game is producing frames, so the menu cannot be interactive before the game starts. The
        // launcher stays shown over the (booting) game until the user clicks Play (which hides it);
        // F1 reopens the menu in-game. BAR_SKIP_LAUNCHER starts with the overlay hidden (headless).

        // Upstream added game modes: start_game now takes a mode id alongside the game id. BAR has
        // no alternate modes, so it starts in the default (empty) mode.
        recomp::start_game(game_id, "");
#ifdef BEETLE_ENABLE_UI
        bar_ui::on_game_started();   // mark game started (enables F1); the launcher stays as an overlay
#endif
    }).detach();
#endif // !BEETLE_ENABLE_FRONTEND

    // ---- Assemble callbacks (field names verified against the vendored headers) ----
    recomp::rsp::callbacks_t rsp_callbacks{};                  // MANDATORY
    rsp_callbacks.get_rsp_microcode = get_rsp_microcode;

    ultramodern::renderer::callbacks_t renderer_callbacks{};   // MANDATORY
#ifdef BEETLE_ENABLE_FRONTEND
    // recompui draws its menus over the game, so it supplies its own RT64 context; use that instead
    // of src/main/rt64_render_context.cpp. bar::frontend::create_render_context adapts the runtime's
    // 3-argument callback to recompui's 4-argument factory, and pins Console presentation so the
    // main-menu film-roll (a VI-origin pan that never redraws) still animates.
    renderer_callbacks.create_render_context = bar::frontend::create_render_context;
#else
    renderer_callbacks.create_render_context = bar_create_rt64_render_context;
#endif

    ultramodern::gfx_callbacks_t gfx_callbacks{};
    gfx_callbacks.create_gfx    = create_gfx;
    gfx_callbacks.create_window = create_window;
    gfx_callbacks.update_gfx    = update_gfx;

    ultramodern::audio_callbacks_t audio_callbacks{};
    audio_callbacks.queue_samples        = queue_samples;
    audio_callbacks.get_frames_remaining = get_frames_remaining;
    audio_callbacks.set_frequency        = set_frequency;

    ultramodern::input::callbacks_t input_callbacks{};
    input_callbacks.poll_input = input_poll;
    input_callbacks.get_input  = input_get;
    input_callbacks.set_rumble = input_set_rumble;
    input_callbacks.get_connected_device_info = input_get_device_info;

    ultramodern::error_handling::callbacks_t error_handling_callbacks{};
    error_handling_callbacks.message_box = message_box;

    ultramodern::threads::callbacks_t threads_callbacks{};
    threads_callbacks.get_game_thread_name = get_game_thread_name;

    recomp::Configuration config{};
    config.project_version          = project_version;
    config.rsp_callbacks            = rsp_callbacks;
    config.renderer_callbacks       = renderer_callbacks;
    config.audio_callbacks          = audio_callbacks;
    config.input_callbacks          = input_callbacks;
    config.gfx_callbacks            = gfx_callbacks;
    config.error_handling_callbacks = error_handling_callbacks;
    config.threads_callbacks        = threads_callbacks;
    // MENU-FPS FIX: BAR's SI (controller) event queue (main.c:311, D_8002F828) is only capacity 3, and our
    // low-level __osSiRawStartDma stub posts an SI completion per call. BAR doesn't drain them all during
    // the menu, so the queue fills with stale completions; with the default requeue_si=true, every new SI
    // completion then BOUNCES (re-queues) off the full queue in a ~15M/sec busy-spin that starves the
    // cooperative scheduler and throttled the menu to ~10fps. SI completions are disposable (live input is
    // re-read from PIF RAM each frame), so drop the excess instead of bouncing it.
    config.message_queue_control.requeue_si = (std::getenv("BAR_REQUEUE_SI") != nullptr);  // R6 bisect: default false (the menu-FPS fix); BAR_REQUEUE_SI=1 reverts to stock true
    // config.window_handle / events_callbacks: defaults are fine for now.

    // Cooperative audio-thread preemption: raise a host "yield now" flag at ~500Hz; a poll injected at every
    // recompiled-function prologue (fix-recompiled.sh rule F) then yields to the audio manager so long
    // straight-line game-thread compute can't starve audio (-> no underrun crackle at a low buffer). The flag
    // is gated to game threads once running, so starting the timer before the game spins up is harmless.
    extern void bar_start_preempt_timer();
    extern void bar_stop_preempt_timer();
    bar_start_preempt_timer();

#ifdef BEETLE_ENABLE_FRONTEND
    // Program identity, primary font and the launcher layout. Must precede recomp::start(), which
    // brings up the renderer — recompui builds its menus during that bring-up, and throws if no
    // primary font has been registered by then.
    bar::frontend::install();
#endif

    // Blocks until the game exits.
    recomp::start(config);
    bar_stop_preempt_timer();
    return EXIT_SUCCESS;
}
