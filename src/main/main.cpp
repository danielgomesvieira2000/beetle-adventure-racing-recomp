// bar_poll_keyboard (defined below) is the single input source — BAR_AUTOPLAY script or live
// keyboard. It feeds BOTH the high-level path (this callback, for ultramodern's osContGetReadData)
// and the low-level SI path (os_unimpl_stubs.cpp's __osSiRawStartDma fill), so input reaches the
// game whichever way it polls.
extern "C" uint16_t bar_poll_keyboard(int port, int8_t* stick_x, int8_t* stick_y);

static bool input_get(int controller_num, uint16_t* buttons, float* x, float* y) {
    if (!bar::input::port_connected(controller_num)) {
        return false;   // this N64 port has no controller / device assigned
    }
    int8_t sx = 0, sy = 0;
    const uint16_t b = bar_poll_keyboard(controller_num, &sx, &sy);
    if (buttons != nullptr) *buttons = b;
    if (x != nullptr)       *x = (float)sx / 80.0f;   // N64 stick range -> ~[-1, 1]
    if (y != nullptr)       *y = (float)sy / 80.0f;
    return true;
}

static void input_set_rumble(int controller_num, bool rumble) {
    bar::input::set_rumble(controller_num, rumble);
}

static ultramodern::input::connected_device_info_t input_get_device_info(int controller_num) {
    using namespace ultramodern::input;
    if (!bar::input::port_connected(controller_num)) {
        return connected_device_info_t{ Device::None, Pak::None };
    }
    // A Rumble Pak is surfaced to the high-level path so ultramodern's osMotorInit succeeds; a
    // Controller Pak is emulated at the SI/joybus level (status bit + mempak), so it reports no
    // high-level pak here (we don't want the runtime treating it as a rumble device).
    // Report the configured accessory. Controller Pak support needs BOTH halves and neither works
    // alone (verified by reverting each):
    //   1. here — ultramodern sets OSContStatus.status = (connected_pak != Pak::None), and BAR gates
    //      its whole pak path on that status. With None it never even issues an SI pak query.
    //   2. os_unimpl_stubs.cpp — answers the SHORT-format status query and serves READ_PAK/WRITE_PAK
    //      against the 32 KiB per-port store, which is where the notes actually live.
    //
    // Pak::ControllerPak was added to the ultramodern fork for this: it reports the accessory as
    // present without osMotorInit accepting the port as a rumble device (it only accepts RumblePak).
    Pak pak = Pak::None;
    switch (bar::input::port_pak(controller_num)) {
        case bar::input_config::PakType::ControllerPak: pak = Pak::ControllerPak; break;
        case bar::input_config::PakType::RumblePak:     pak = Pak::RumblePak;     break;
        case bar::input_config::PakType::None:          pak = Pak::None;          break;
    }
    return connected_device_info_t{ Device::Controller, pak };
}

// Keyboard -> N64 controller (port 0). BAR reads the pad via the raw SI/PIF path, so
// __osSiRawStartDma_recomp (os_unimpl_stubs.cpp) calls this to fill the read buffer. Uses Win32 async
// key state, gated to when the game window is focused. Bindings (port 0):
//   Analog stick: Arrows   A: X   B: Z   Start: Enter   Z-trigger: Shift   L: Q   R: W   C-buttons: I/J/K/L   D-pad: T/F/G/H
// Scripted auto-input for headless menu/race testing. Set BAR_AUTOPLAY to a space-separated
// sequence of "frames:hexbuttons" phases, played in order then held neutral. Hex is the N64 button
// mask (START=1000 A=8000 B=4000 Z=2000; d-pad U=0800 D=0400 L=0200 R=0100). D-pad bits also drive
// the analog stick so menus reading either respond. Bypasses the focus gate.
// Example: BAR_AUTOPLAY="180:0 12:1000 60:0 12:8000"  -> wait, tap START, wait, tap A.
static uint16_t bar_autoplay_poll(const char* script, int8_t* stick_x, int8_t* stick_y) {
    struct Phase { int dur; uint16_t btn; };
    static std::vector<Phase> phases;
    static bool parsed = false;
    static size_t idx = 0;
    static int held = 0;
    static unsigned long long fc = 0;
    if (!parsed) {
        parsed = true;
        for (const char* p = script; *p; ) {
            while (*p == ' ' || *p == '\t') ++p;
            if (!*p) break;
            char* e = nullptr;
            long dur = std::strtol(p, &e, 10);
            uint16_t btn = 0;
            if (e && *e == ':') btn = (uint16_t)std::strtol(e + 1, &e, 16);
            p = (e && e != p) ? e : p + 1;
            if (dur > 0) phases.push_back({(int)dur, btn});
        }
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] AUTOPLAY: %zu phases parsed\n", phases.size());
        std::fflush(stderr);
    }
    ++fc;
    uint16_t btn = 0;
    if (idx < phases.size()) {
        btn = phases[idx].btn;
        if (++held >= phases[idx].dur) {
            held = 0; ++idx;
            std::fprintf(stderr, "[beetle-adventure-racing-recomp] AUTOPLAY -> phase %zu/%zu @fc=%llu next=0x%04X\n",
                         idx, phases.size(), fc, (unsigned)(idx < phases.size() ? phases[idx].btn : 0));
            std::fflush(stderr);
        }
    }
    int sx = 0, sy = 0;
    if (btn & 0x0800) sy += 80;
    if (btn & 0x0400) sy -= 80;
    if (btn & 0x0200) sx -= 80;
    if (btn & 0x0100) sx += 80;
    if (stick_x) *stick_x = (int8_t)sx;
    if (stick_y) *stick_y = (int8_t)sy;
    return btn;
}

// BAR_SHOTS="frame:path frame:path ..." — request an internal-render screenshot (RT64 GPU readback -> PNG)
// at each listed frame, on the SAME frame counter as BAR_AUTOPLAY so captures line up with scripted input.
extern "C" void bar_rt64_request_screenshot(const char *path);
static void bar_shots_poll() {
    struct Shot { unsigned long frame; std::string path; };
    static std::vector<Shot> shots;
    static bool parsed = false;
    static size_t idx = 0;
    static unsigned long long fc = 0;
    if (!parsed) {
        parsed = true;
        if (const char *s = std::getenv("BAR_SHOTS")) {
            for (const char *p = s; *p; ) {
                while (*p == ' ' || *p == '\t') ++p;
                if (!*p) break;
                char *e = nullptr;
                long fr = std::strtol(p, &e, 10);
                if (e && *e == ':') {
                    const char *ps = e + 1, *pe = ps;
                    while (*pe && *pe != ' ' && *pe != '\t') ++pe;
                    if (fr > 0 && pe > ps) shots.push_back({ (unsigned long)fr, std::string(ps, pe - ps) });
                    p = pe;
                } else {
                    p = (e && e != p) ? e : p + 1;
                }
            }
            std::fprintf(stderr, "[beetle-adventure-racing-recomp] BAR_SHOTS: %zu scheduled\n", shots.size());
        }
    }
    ++fc;
    while (idx < shots.size() && fc >= shots[idx].frame) {
        bar_rt64_request_screenshot(shots[idx].path.c_str());
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] BAR_SHOTS -> %s @fc=%llu\n", shots[idx].path.c_str(), (unsigned long long)fc);
        ++idx;
    }
}

// BAR_SHOT_BURST="fc:dir:count" — at input frame fc, tell RT64 to capture the next `count` presents to
// dir/fNNNN.png (one per present). For animations the input timeline can't sample (film-roll transition:
// the game blocks in a render loop and stops polling input, so BAR_SHOTS frames freeze mid-roll). Trigger
// a few frames BEFORE the transition, while fc is still advancing; RT64 then counts presents on its own.
extern "C" void bar_rt64_start_burst(const char *dir, int count);
static void bar_burst_poll() {
    static bool parsed = false, fired = false;
    static unsigned long fc_trigger = 0; static int count = 0; static std::string dir;
    static unsigned long long fc = 0;
    if (!parsed) {
        parsed = true;
        if (const char *s = std::getenv("BAR_SHOT_BURST")) {
            std::string spec(s);
            size_t c1 = spec.find(':'), c2 = (c1 == std::string::npos) ? std::string::npos : spec.find(':', c1 + 1);
            if (c2 != std::string::npos) {
                fc_trigger = std::strtoul(spec.substr(0, c1).c_str(), nullptr, 10);
                dir = spec.substr(c1 + 1, c2 - c1 - 1);
                count = std::atoi(spec.substr(c2 + 1).c_str());
            }
            std::fprintf(stderr, "[beetle-adventure-racing-recomp] BAR_SHOT_BURST: fc=%lu dir=%s count=%d\n", fc_trigger, dir.c_str(), count);
        }
    }
    ++fc;
    if (!fired && count > 0 && fc >= fc_trigger) {
        fired = true;
        bar_rt64_start_burst(dir.c_str(), count);
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] BAR_SHOT_BURST triggered @fc=%llu\n", (unsigned long long)fc);
        std::fflush(stderr);
    }
}

// The gated per-port input entry. Both the low-level SI/PIF stub (os_unimpl_stubs.cpp) and the
// high-level input_get callback call this for each port. The per-port device + rebindable bindings
// live in bar::input (bar_input.cpp); this wrapper keeps the GLOBAL gates + port-0 test tooling:
//   * BAR_SHOTS / BAR_SHOT_BURST screenshot scheduling (once per SI poll, port 0),
//   * BAR_AUTOPLAY scripted input (headless testing, port 0),
//   * freeze while the menu owns input, and the window-focus gate.
extern "C" uint16_t bar_poll_keyboard(int port, int8_t* stick_x, int8_t* stick_y) {
    if (stick_x) *stick_x = 0;
    if (stick_y) *stick_y = 0;
    if (port < 0 || port >= 4) return 0;
    if (port == 0) {
        bar_shots_poll();
        bar_burst_poll();
        static const char* autoplay = std::getenv("BAR_AUTOPLAY");
        if (autoplay && *autoplay) return bar_autoplay_poll(autoplay, stick_x, stick_y);
    }
#ifdef BEETLE_ENABLE_UI
    // While the launcher/settings/cheats/controls overlay is open, freeze game input so menu
    // navigation (arrows/enter) doesn't also drive the car.
    if (bar_ui::menu_capturing_input()) return 0;
#endif
#ifdef BEETLE_ENABLE_FRONTEND
    // Same idea, but asked of recompui, which reports whether a context is ACTUALLY capturing input
    // rather than merely being open. That distinction matters: the legacy check froze game input for
    // as long as its overlay existed, so a normal launch reached the game with a dead keyboard.
    if (bar::frontend::menu_capturing_input()) return 0;
#endif
    // Only read the keyboard while our window actually holds input focus, so we don't drive the car
    // when the user has tabbed away. SDL tracks focus the same way on every platform.
    if (g_window != nullptr && !(SDL_GetWindowFlags(g_window) & SDL_WINDOW_INPUT_FOCUS)) return 0;
    return bar::input::resolve_port(port, stick_x, stick_y);
}

// Error handling (error_handling::callbacks_t). ultramodern calls this for FATAL startup errors — most
// importantly the renderer-setup failures in events.cpp (Vulkan loader missing / no compatible GPU), after
// which it throws to abort. Route it through a real SDL dialog (bar_user_message, forward-declared above)
// rather than only stderr, so a player who double-clicked the app actually sees why it refused to start
// instead of being left with a silent black window. bar_user_message still logs the same text to stderr.
static void message_box(const char* msg) { bar_user_message(SDL_MESSAGEBOX_ERROR, msg); }

// "Restart Game" (pause menu): the recompiled game can't be cleanly re-entered in-process, so restart
// the whole process — relaunch the exe with the same arguments, then quit this instance. Declared in
// src/ui/bar_ui.cpp. Non-static so the UI TU can link to it.
void bar_restart_game() {
#ifdef _WIN32
    char exe[MAX_PATH] = {};
    GetModuleFileNameA(nullptr, exe, MAX_PATH);
    std::string cmd = GetCommandLineA();   // relaunch with the same args (ROM path, etc.) + same cwd
    STARTUPINFOA si{}; si.cb = sizeof(si);
    PROCESS_INFORMATION pi{};
    if (CreateProcessA(exe, cmd.empty() ? nullptr : cmd.data(), nullptr, nullptr, FALSE, 0,
                       nullptr, nullptr, &si, &pi)) {
        CloseHandle(pi.hProcess);
        CloseHandle(pi.hThread);
    } else {
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] restart: CreateProcess failed (%lu)\n", (unsigned long)GetLastError());
    }
#endif
    ultramodern::quit();   // exit this instance (the fresh one takes over)
}

