static ultramodern::gfx_callbacks_t::gfx_data_t create_gfx() {
    SDL_SetMainReady();
    // Windows DPI awareness. SDL_WINDOW_ALLOW_HIGHDPI alone is not enough here: unless the PROCESS is
    // marked DPI-aware before SDL_Init, Windows hands a scaled desktop to the app and lies about
    // sizes. On a 1920x1080 display at 125% that means SDL sees 1536x864, so the renderer draws at
    // physical resolution while the window is measured in logical pixels — the UI overflows the
    // window (its title clips) and, worse, mouse coordinates land about 1.25x off, so clicking a
    // menu entry activates a different one. Both hints must be set before SDL_Init to take effect.
    SDL_SetHint(SDL_HINT_WINDOWS_DPI_AWARENESS, "permonitorv2");
    // DPI_SCALING is deliberately OFF. With it on, SDL reports window geometry and mouse positions
    // in DPI-scaled logical units while the drawable — and therefore everything RT64 and recompui
    // lay out — stays in physical pixels. At 125% that is a 1.25x disagreement between where the UI
    // draws a button and where a click is reported, which shows up as having to click well away
    // from a menu entry to hit it. Awareness alone keeps both sides in physical pixels.
    SDL_SetHint(SDL_HINT_WINDOWS_DPI_SCALING, "0");
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_EVENTS | SDL_INIT_GAMECONTROLLER | SDL_INIT_AUDIO) != 0) {
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] SDL_Init failed: %s\n", SDL_GetError());
    }
    return nullptr;   // gfx_data_t is unused; the window is tracked in g_window
}

static ultramodern::renderer::WindowHandle create_window(ultramodern::gfx_callbacks_t::gfx_data_t /*data*/) {
    // Default to a 4:3 window. BAR_WINDOW_SIZE=WxH overrides it — handy for widescreen users and for
    // QA'ing the letterbox present modes (Pillarbox/Crop/Stretch), which only differ on a non-4:3 window.
    int win_w = 960, win_h = 720;
    if (const char *ws = std::getenv("BAR_WINDOW_SIZE")) {
        int w = 0, h = 0;
        if (std::sscanf(ws, "%dx%d", &w, &h) == 2 && w >= 320 && h >= 240) {
            win_w = w;
            win_h = h;
        }
    }
    // RT64's backend is per-platform: D3D12 on Windows (it binds to the raw HWND, so the SDL window needs
    // no graphics-API flag), Vulkan on Linux/Android, Metal on macOS. The Vulkan and Metal backends create
    // their swapchain surface *through SDL* (SDL_Vulkan_CreateSurface / SDL_Metal_CreateView), which requires
    // the window to have been created with the matching flag. Without it SDL fails the surface call with
    // "The specified window isn't a Vulkan window" and RT64 then dereferences the null surface and segfaults.
    // We deliberately omit the flag on Windows so RT64's default D3D12 path is unaffected.
    Uint32 window_flags = SDL_WINDOW_RESIZABLE | SDL_WINDOW_ALLOW_HIGHDPI;
#if defined(__APPLE__)
    window_flags |= SDL_WINDOW_METAL;
#elif !defined(_WIN32)
    window_flags |= SDL_WINDOW_VULKAN;
#endif
    g_window = SDL_CreateWindow("Beetle Adventure Racing: Recompiled",
        SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, win_w, win_h,
        window_flags);
    if (g_window == nullptr) {
        // With SDL_WINDOW_VULKAN set, SDL tries to load the Vulkan loader here — so this branch also fires
        // when the machine has no usable Vulkan driver at all. Tell the player how to fix it rather than
        // leaving them with a silent black window / a stderr line no GUI launcher ever shows.
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] SDL_CreateWindow failed: %s\n", SDL_GetError());
#if !defined(_WIN32) && !defined(__APPLE__)
        bar_user_message(SDL_MESSAGEBOX_ERROR,
            "Beetle Adventure Racing: Recompiled could not create a Vulkan window.\n\n"
            "Your system is most likely missing a Vulkan driver. Install your GPU's Vulkan support:\n"
            "  - AMD / Intel (Mesa):  sudo apt install mesa-vulkan-drivers\n"
            "  - NVIDIA:              install the proprietary NVIDIA driver package\n"
            "  - Then verify with:    vulkaninfo   (from the vulkan-tools package)\n\n"
            "The detailed SDL error was printed to the terminal.");
        // Fatal and unrecoverable: exit cleanly right here rather than returning an empty handle and letting
        // RT64 crash on a null window (or raising a second, vaguer dialog from ultramodern's setup-failure
        // path). The modal dialog above has already been dismissed by the user by this point.
        std::_Exit(EXIT_FAILURE);
#endif
        return {};
    }
#ifdef BEETLE_ENABLE_UI
    // Register the RmlUi render hooks now, before the gfx thread constructs RT64 (recomp::start
    // calls create_window on this thread *before* spawning the gfx thread that runs
    // create_render_context → app->setup, which is when RT64 fires the UI init hook).
    bar_ui::install(g_window, g_default_rom_path);
#endif

#ifdef _WIN32
    // Windows: RT64 attaches to the native HWND and needs the id of the thread that owns the window.
    // create_window runs on the same (main) thread that pumps update_gfx below, so that's this thread.
    SDL_SysWMinfo wm_info;
    SDL_VERSION(&wm_info.version);
    if (SDL_GetWindowWMInfo(g_window, &wm_info) != SDL_TRUE) {
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] SDL_GetWindowWMInfo failed: %s\n", SDL_GetError());
        return {};
    }
    return ultramodern::renderer::WindowHandle{ wm_info.info.win.window, GetCurrentThreadId() };
#else
    // Linux/Android: WindowHandle is the SDL_Window* itself (RT64 derives the native handle from it).
    return g_window;
#endif
}

static void update_gfx(ultramodern::gfx_callbacks_t::gfx_data_t /*data*/) {
#ifdef BEETLE_ENABLE_FRONTEND
    // recompinput owns the SDL queue and must be its ONLY poller -- a second loop would race it and
    // each would swallow events the other needed. It is pumped here rather than from input_poll
    // because this callback runs even with no game started, which is where the launcher lives.
    bar::frontend::pump_events();
#else
    SDL_Event event;
    while (SDL_PollEvent(&event)) {
        if (event.type == SDL_QUIT) {
            ultramodern::quit();
            continue;
        }
        // Game controller hotplug. SDL queues a DEVICEADDED for controllers already present at init,
        // so this also picks up controllers plugged in before launch. bar::input tracks all of them
        // (up to 4 ports can be driven); the Controls dialog assigns which pad drives which port.
        if (event.type == SDL_CONTROLLERDEVICEADDED) {
            bar::input::on_controller_added(event.cdevice.which);
#ifdef BEETLE_ENABLE_UI
            bar_publish_devices();
#endif
            continue;
        }
        if (event.type == SDL_CONTROLLERDEVICEREMOVED) {
            bar::input::on_controller_removed(event.cdevice.which);
#ifdef BEETLE_ENABLE_UI
            bar_publish_devices();
#endif
            continue;
        }
#ifdef BEETLE_ENABLE_UI
        // While the Controls dialog is waiting for a key/button to (re)assign a binding, DON'T consume
        // Esc/F1, the Back button, or synthesize menu-nav — forward the raw event so it can be captured
        // as the binding (Esc cancels the capture inside bar_ui). Skip these three intercepts entirely.
        const bool rebinding = bar_ui::rebind_listening();
        // Esc / F1 toggle the in-game pause menu (pauses the simulation; no effect pre-game — the
        // launcher is already up). The game never reads these keys (game input is GetAsyncKeyState /
        // controller based), so we consume them here.
        if (!rebinding && event.type == SDL_KEYDOWN && event.key.repeat == 0 &&
            (event.key.keysym.sym == SDLK_ESCAPE || event.key.keysym.sym == SDLK_F1)) {
            bar_ui::toggle_pause_menu();
            continue;
        }
        // Controller Back/View/Select button also toggles the pause menu (N64 pads have no such
        // button, so it never conflicts with game input).
        if (!rebinding && event.type == SDL_CONTROLLERBUTTONDOWN && event.cbutton.button == SDL_CONTROLLER_BUTTON_BACK) {
            bar_ui::toggle_pause_menu();
            continue;
        }
        // Controller navigation of the menu: translate buttons to the keyboard nav the menu already
        // handles (D-pad -> arrows = move focus; A -> Enter = activate). Synthesize a key event and feed
        // it through the same path. Only while the menu owns input (and not while capturing a rebind).
        if (!rebinding && bar_ui::menu_capturing_input() && event.type == SDL_CONTROLLERBUTTONDOWN) {
            SDL_Keycode key = 0;
            switch (event.cbutton.button) {
                case SDL_CONTROLLER_BUTTON_DPAD_UP:    key = SDLK_UP;     break;
                case SDL_CONTROLLER_BUTTON_DPAD_DOWN:  key = SDLK_DOWN;   break;
                case SDL_CONTROLLER_BUTTON_DPAD_LEFT:  key = SDLK_LEFT;   break;
                case SDL_CONTROLLER_BUTTON_DPAD_RIGHT: key = SDLK_RIGHT;  break;
                case SDL_CONTROLLER_BUTTON_A:          key = SDLK_RETURN; break;
                default: break;
            }
            if (key != 0) {
                SDL_Event k{};
                k.type = SDL_KEYDOWN;
                k.key.type = SDL_KEYDOWN;
                k.key.state = SDL_PRESSED;
                k.key.repeat = 0;
                k.key.keysym.sym = key;
                k.key.keysym.scancode = SDL_GetScancodeFromKey(key);
                bar_ui::handle_sdl_event(k);
            }
            continue;
        }
        // While the launcher/settings/cheats menu owns input, forward events to RmlUi (drained on
        // the render thread). Once the game starts, the menu hides and input goes to the game.
        if (bar_ui::menu_capturing_input()) {
            bar_ui::handle_sdl_event(event);
        }
#endif
    }
#endif // BEETLE_ENABLE_FRONTEND

    // Shared by BOTH builds: the game's own per-frame input work. The frontend replaces the event
    // PUMP, not the N64-port input path -- and mempak_flush_all in particular must keep running, or
    // Controller Pak saves would never reach disk.
    bar::input::sample_all_ports();   // refresh every assigned pad's snapshot on this (main) thread
    bar::input::flush_rumble();       // issue SDL rumble for any port that wants it (main thread)
    bar::input::mempak_flush_all();   // persist any Controller Pak writes (cheap no-op when clean)
}

// Audio (audio_callbacks_t) — SDL2 queued-audio backend.
// The libultra->ultramodern AI chain (librecomp/src/ai.cpp -> ultramodern/src/audio.cpp) delivers the
// game's PCM here as `count` interleaved-stereo int16 samples pointing straight into RDRAM (no swap done
// upstream). EMPIRICALLY VERIFIED (captured BAR menu music, offline autocorrelation): the raw int16
// values are ALREADY correct host-order (librecomp's RDRAM word-swizzle yields correct s16 on raw read);
// byteswapping them produces white-noise "screeching". The word-swizzle delivers the pair as [R,L], so
// we channel-swap to [L,R] (matches Zelda64Recompiled's backend). BAR_AUDIO_XFORM overrides:
//   0 = as-is, 1 = byteswap only, 2 = channel-swap only [default, correct], 3 = byteswap + channel-swap.
//
// SAFETY: the output device is opened (and sound produced) ONLY when BAR_AUDIO_PLAY is set. By default —
// and while verifying correctness — NO device is opened and NOTHING plays. BAR_AUDIO_CAPTURE=<path> dumps
// the raw (untransformed) received stream so the correct transform can be checked offline without audio.
static SDL_AudioDeviceID g_audio_dev = 0;
static uint32_t g_dev_freq  = 0;        // freq the SDL device is currently open at
static uint32_t g_game_freq = 0;        // last freq the game requested (for capture/WAV)
static constexpr int kBarBytesPerFrame = 2 * (int)sizeof(int16_t);   // stereo s16
static std::FILE* g_audio_capture = nullptr;
static size_t g_audio_capture_bytes = 0;

static bool bar_audio_play_enabled() {
    // Audio output ON by default; BAR_NO_AUDIO disables the device (and the ucode, see get_rsp_microcode).
    static const bool on = std::getenv("BAR_NO_AUDIO") == nullptr;
    return on;
}
static int bar_audio_xform() {
    static const int x = []{ const char* e = std::getenv("BAR_AUDIO_XFORM"); return e ? std::atoi(e) : 2; }();
    return x;
}

static void bar_open_audio(uint32_t freq) {
    if (freq == 0) return;
    g_game_freq = freq;
    if (g_audio_capture == nullptr) {
        static bool tried = false;
        if (!tried) { tried = true;
            const char* cap = std::getenv("BAR_AUDIO_CAPTURE");
            if (cap && *cap) { g_audio_capture = std::fopen(cap, "wb");
                std::fprintf(stderr, "[beetle-adventure-racing-recomp] audio capture -> %s\n", cap); }
        }
    }
    if (!bar_audio_play_enabled()) return;          // muted: never open a device, never play
    if (g_audio_dev != 0 && g_dev_freq == freq) return;
    if (g_audio_dev != 0) { SDL_CloseAudioDevice(g_audio_dev); g_audio_dev = 0; }
    if (SDL_WasInit(SDL_INIT_AUDIO) == 0 && SDL_InitSubSystem(SDL_INIT_AUDIO) != 0) {
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] SDL_InitSubSystem(AUDIO) failed: %s\n", SDL_GetError());
        return;
    }
    SDL_AudioSpec want{}, have{};
    want.freq = (int)freq; want.format = AUDIO_S16SYS; want.channels = 2; want.samples = 1024; want.callback = nullptr;
    g_audio_dev = SDL_OpenAudioDevice(nullptr, 0, &want, &have, 0);
    if (g_audio_dev == 0) {
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] SDL_OpenAudioDevice failed: %s\n", SDL_GetError());
        return;
    }
    g_dev_freq = (uint32_t)have.freq;
    SDL_PauseAudioDevice(g_audio_dev, 0);
}

static void queue_samples(int16_t* samples, size_t count) {
    if (samples == nullptr || count == 0) return;
    // Capture the RAW received stream (no transform) for offline analysis, capped at ~16 MB.
    if (g_audio_capture && g_audio_capture_bytes < (16u << 20)) {
        size_t n = std::fwrite(samples, sizeof(int16_t), count, g_audio_capture);
        g_audio_capture_bytes += n * sizeof(int16_t);
    }
    if (g_audio_dev == 0) return;                    // muted (default) — produce no sound
    const int xf = bar_audio_xform();
    const bool byteswap = (xf == 1 || xf == 3);
    const bool chanswap = (xf == 2 || xf == 3);
    static std::vector<int16_t> out;
    out.resize(count);
    for (size_t i = 0; i < count; i++) {
        uint16_t v = (uint16_t)samples[i];
        out[i] = byteswap ? (int16_t)(uint16_t)((v >> 8) | (v << 8)) : (int16_t)v;
    }
    if (chanswap) { for (size_t i = 0; i + 1 < count; i += 2) { int16_t t = out[i]; out[i] = out[i+1]; out[i+1] = t; } }
    { static const bool dbg = std::getenv("BAR_AUDIO_DBG") != nullptr; if (dbg) {
        extern int g_bar_audio_peak; extern long g_bar_audio_clip;
        for (size_t i = 0; i < count; i++) { int a = out[i] < 0 ? -(int)out[i] : out[i];
            if (a > g_bar_audio_peak) g_bar_audio_peak = a; if (a >= 32760) g_bar_audio_clip++; } } }
    SDL_QueueAudio(g_audio_dev, out.data(), (Uint32)(count * sizeof(int16_t)));
}

int  g_bar_audio_peak = 0;   // diag (BAR_AUDIO_DBG): peak |sample| + saturation count
long g_bar_audio_clip = 0;

static size_t get_frames_remaining() {
    if (g_audio_dev == 0) return 0;
    size_t frames = (size_t)(SDL_GetQueuedAudioSize(g_audio_dev) / (Uint32)kBarBytesPerFrame);
    { static const bool dbg = std::getenv("BAR_AUDIO_DBG") != nullptr; if (dbg) {
        // Inter-call wall delta (called ~once per game frame). Flag genuine near-underruns (queue almost
        // empty) and egregious single-frame stalls (>50 ms = >3 VI) — not normal 16.6 ms frames.
        static auto last = std::chrono::steady_clock::now(); auto now = std::chrono::steady_clock::now();
        double dms = std::chrono::duration<double, std::milli>(now - last).count(); last = now;
        if ((frames < 150 && frames > 0) || dms > 50.0) { std::fprintf(stderr, "[beetle-adventure-racing-recomp] audio LOW: queued=%zu frameDelta=%.1fms\n", frames, dms); std::fflush(stderr); }
        static size_t minq = (size_t)-1, maxq = 0; static int n = 0;
        if (frames < minq) minq = frames; if (frames > maxq) maxq = frames;
        if ((++n % 60) == 0) {
            std::fprintf(stderr, "[beetle-adventure-racing-recomp] audio: queued now=%zu min=%zu max=%zu | peak=%d clipped=%ld%s\n",
                         frames, minq, maxq, g_bar_audio_peak, g_bar_audio_clip,
                         (minq == 0) ? "  <<< UNDERRUN" : "");
            std::fflush(stderr); minq = (size_t)-1; maxq = 0; g_bar_audio_peak = 0; g_bar_audio_clip = 0;
        } } }
    return frames;
}

